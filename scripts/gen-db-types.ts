// npm run db:types: regenerates src/server/repository/database.types.ts from the LOCAL stack's schema
// (run `npm run db:reset` first so it matches supabase/migrations/). The CLI prints unformatted
// TypeScript; oxfmt (pinned) formats it.
import {execFileSync} from 'node:child_process';
import {writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {ROOT} from './lib/local-supabase';

const OUT=join(ROOT,'src/server/repository/database.types.ts');
const HEADER='// Generated by `npm run db:types` (supabase gen types) from supabase/migrations/. Do not edit by hand.\n\n';

const types=execFileSync('npx',['supabase','gen','types','typescript','--local','--schema','public'],{cwd:ROOT,encoding:'utf8',stdio:['ignore','pipe','pipe']});
writeFileSync(OUT,HEADER+types);
execFileSync('npx',['--yes','oxfmt@0.73.0',OUT],{cwd:ROOT,stdio:['ignore','ignore','inherit']});
console.log('Wrote src/server/repository/database.types.ts');
